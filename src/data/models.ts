/**
 * Parse a release date like "2024-07" or just "2025" into a sortable integer.
 * Year-only entries are treated as mid-year so they land between explicit
 * months of the same year.
 */
function parseReleased(s: string): number {
  const m = s.match(/^(\d{4})(?:-(\d{2}))?/);
  if (!m) return Number.MAX_SAFE_INTEGER;
  const year = parseInt(m[1], 10);
  const month = m[2] ? parseInt(m[2], 10) : 6;
  return year * 100 + month;
}

/**
 * Public model list — sorted by release date (oldest first) and re-numbered
 * Dex #001..#NN. fullName is the stable identifier used by sprite lookup,
 * so renumbering Dex IDs here is safe.
 */
export const MODELS: AIModel[] = [...RAW_MODELS]
  .sort((a, b) => parseReleased(a.released) - parseReleased(b.released))
  .map((m, i) => ({ ...m, id: i + 1 }));

