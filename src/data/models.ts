export function statTotal(m: AIModel): number {
  const s = m.stats;
  return s.hp + s.attack + s.defense + s.spAttack + s.spDefense + s.speed;
}

export function chainOf(model: AIModel): AIModel[] {
  if (!model.evolutionChain) return [model];
  return MODELS.filter((m) => m.evolutionChain === model.evolutionChain).sort(
    (a, b) => (a.evolutionStage ?? 0) - (b.evolutionStage ?? 0)
  );
}
